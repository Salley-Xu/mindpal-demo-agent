def main():
    base = PROJECT_ROOT / "data" / "intent" / "intent_seed_v1_5.jsonl"
    items = [IntentData.model_validate(json.loads(l)) for l in open(base, encoding="utf-8") if l.strip()]

    # 避免与已有文本重复
    existing = {d.text for d in items}
    added = 0
    for i, (text, note) in enumerate(RISK):
        if text in existing:
            continue
        items.append(IntentData(
            id=f"iseed_risk_{i:03d}",
            conversation=[{"role": "user", "content": text}],
            text=text, labels=[IntentLabel.HIGH_RISK_EXPRESSION],
            source="template", difficulty="hard", notes=f"implicit_risk:{note}",
        ))
        added += 1

    with open(base, "w", encoding="utf-8") as f:
        for d in items:
            f.write(json.dumps(d.model_dump(), ensure_ascii=False) + "\n")

    from collections import Counter
    hr = sum(1 for d in items if any(l.value == "high_risk_expression" for l in d.labels))
    print(f"[OK] 隐式高危扩充完成: 新增 {added} 条 -> 总计 {len(items)} 条, high_risk_expression={hr}")


if __name__ == "__main__":
    main()
