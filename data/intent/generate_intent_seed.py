# =====================================================================
# 合并 + 统计 + 写入
# =====================================================================

def main():
    out_path = PROJECT_ROOT / "data" / "intent" / "intent_seed_v1.jsonl"
    # 校验
    from collections import Counter
    label_cnt = Counter()
    multi = 0
    for d in SEED:
        for lab in d.labels:
            label_cnt[lab.value] += 1
        if len(d.labels) > 1:
            multi += 1

    # 写入
    with open(out_path, "w", encoding="utf-8") as f:
        for d in SEED:
            f.write(json.dumps(d.model_dump(), ensure_ascii=False) + "\n")

    print(f"[OK] 写入 {len(SEED)} 条 -> {out_path.name}")
    print(f"   标签分布: {dict(label_cnt)}")
    print(f"   multi-label: {multi}/{len(SEED)} = {multi/len(SEED):.3f}")
    # 检查每标签 >= 60
    missing = {lab: n for lab, n in label_cnt.items() if n < 60}
    print(f"   不足 60 的标签: {missing if missing else '无'}")
    hn = sum(1 for d in SEED if d.notes and '硬负' in (d.notes or '') or d.id.startswith('iseed_hn'))
    print(f"   硬负样本数: {hn}")


if __name__ == "__main__":
    main()


